CREATE TABLE "user" (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(100) NOT NULL,
    password      VARCHAR(100) NOT NULL,
    email         VARCHAR(100) NOT NULL,
    role          VARCHAR(20),
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP,
    google_id     VARCHAR(255),
    display_name  VARCHAR(100),
    first_name    VARCHAR(100),
    last_name     VARCHAR(100),
    CONSTRAINT uq_user_username  UNIQUE (username),
    CONSTRAINT uq_user_google_id UNIQUE (google_id)
);

CREATE TABLE coffee_bean (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(50)  NOT NULL,
    origin            VARCHAR(50)  NOT NULL,
    roast_level       VARCHAR(15)  NOT NULL,
    processing_method VARCHAR(50),
    roaster_name      VARCHAR(50)  NOT NULL,
    roast_date        DATE,
    price             DOUBLE PRECISION,
    altitude          INTEGER,
    tasting_notes     VARCHAR(255),
    favorite          BOOLEAN      NOT NULL DEFAULT FALSE,
    weight_grams      INTEGER,
    user_id           BIGINT,
    photo_url         VARCHAR(255),
    finished          BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_coffee_bean_user FOREIGN KEY (user_id) REFERENCES "user" (id)
);

CREATE TABLE brew_entry (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bean_id           BIGINT           NOT NULL,
    user_id           BIGINT,
    "method"          VARCHAR(50)      NOT NULL,
    grind_size        DOUBLE PRECISION,
    water_temp_c      DOUBLE PRECISION,
    rating            DOUBLE PRECISION,
    brewed_at         TIMESTAMP        NOT NULL,
    brew_time_seconds DOUBLE PRECISION,
    dose_grams        DOUBLE PRECISION NOT NULL,
    water_grams       DOUBLE PRECISION,
    yield_grams       DOUBLE PRECISION,
    notes             VARCHAR(100),
    CONSTRAINT fk_brew_entry_bean FOREIGN KEY (bean_id) REFERENCES coffee_bean (id),
    CONSTRAINT fk_brew_entry_user FOREIGN KEY (user_id) REFERENCES "user" (id)
);

CREATE TABLE flavor_note (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(50) NOT NULL,
    category  VARCHAR(50) NOT NULL,
    user_id   BIGINT,
    CONSTRAINT fk_flavor_note_user FOREIGN KEY (user_id) REFERENCES "user" (id)
);

CREATE TABLE coffee_bean_flavor_note (
    coffee_bean_id  BIGINT NOT NULL,
    flavor_note_id  BIGINT NOT NULL,
    PRIMARY KEY (coffee_bean_id, flavor_note_id),
    CONSTRAINT fk_cbfn_bean   FOREIGN KEY (coffee_bean_id) REFERENCES coffee_bean (id),
    CONSTRAINT fk_cbfn_flavor FOREIGN KEY (flavor_note_id) REFERENCES flavor_note (id)
);

CREATE TABLE refresh_token (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash  VARCHAR(64) NOT NULL,
    user_id     BIGINT      NOT NULL,
    expires_at  TIMESTAMP   NOT NULL,
    used        BOOLEAN     NOT NULL DEFAULT FALSE,
    remember_me BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP   NOT NULL,
    CONSTRAINT uq_refresh_token_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_token_user FOREIGN KEY (user_id) REFERENCES "user" (id)
);

CREATE TABLE cafe_location (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(50) NOT NULL,
    city       VARCHAR(50),
    address    VARCHAR(100),
    rating     DOUBLE PRECISION,
    instagram  VARCHAR(100),
    latitude   DOUBLE PRECISION,
    longitude  DOUBLE PRECISION,
    user_id    BIGINT,
    CONSTRAINT fk_cafe_location_user FOREIGN KEY (user_id) REFERENCES "user" (id)
);

CREATE TABLE audit_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_username  VARCHAR(100) NOT NULL,
    target_user_id  BIGINT       NOT NULL,
    action          VARCHAR(20)  NOT NULL,
    old_value       VARCHAR(255),
    new_value       VARCHAR(255),
    created_at      TIMESTAMP
);

CREATE TABLE report (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT      NOT NULL,
    period_type       VARCHAR(10) NOT NULL,
    period_start      DATE        NOT NULL,
    period_end        DATE        NOT NULL,
    generated_at      TIMESTAMP   NOT NULL,
    source            VARCHAR(10),
    brew_count        INTEGER     NOT NULL,
    average_rating    DOUBLE PRECISION,
    top_bean_name     VARCHAR(50),
    most_used_method  VARCHAR(50),
    total_dose_grams  DOUBLE PRECISION,
    brews_per_day     TEXT,
    method_breakdown  TEXT,
    rating_trend      TEXT,
    CONSTRAINT uq_report_user_period UNIQUE (user_id, period_type, period_start),
    CONSTRAINT fk_report_user FOREIGN KEY (user_id) REFERENCES "user" (id)
);

CREATE TABLE aggregate_report (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_type       VARCHAR(10) NOT NULL,
    period_start      DATE        NOT NULL,
    period_end        DATE        NOT NULL,
    generated_at      TIMESTAMP   NOT NULL,
    source            VARCHAR(10),
    brew_count        INTEGER     NOT NULL,
    active_users      INTEGER     NOT NULL,
    average_rating    DOUBLE PRECISION,
    top_bean_name     VARCHAR(50),
    most_used_method  VARCHAR(50),
    total_dose_grams  DOUBLE PRECISION,
    brews_per_day     TEXT,
    method_breakdown  TEXT,
    rating_trend      TEXT,
    CONSTRAINT uq_aggregate_report_period UNIQUE (period_type, period_start)
);

CREATE INDEX idx_coffee_bean_user     ON coffee_bean (user_id);
CREATE INDEX idx_brew_entry_bean      ON brew_entry (bean_id);
CREATE INDEX idx_brew_entry_user_date ON brew_entry (user_id, brewed_at);
CREATE INDEX idx_flavor_note_user     ON flavor_note (user_id);
CREATE INDEX idx_cafe_location_user   ON cafe_location (user_id);
CREATE INDEX idx_refresh_token_user   ON refresh_token (user_id);