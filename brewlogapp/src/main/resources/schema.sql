CREATE TABLE IF NOT EXISTS audit_log(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_username  VARCHAR(100) NOT NULL,
    target_user_id  BIGINT       NOT NULL,
    action          VARCHAR(20)  NOT NULL,
    old_value       VARCHAR(255),
    new_value       VARCHAR(255),
    created_at      TIMESTAMP
);

CREATE TABLE IF NOT EXISTS report(
                                     id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     user_id           BIGINT NOT NULL,
                                     period_type       VARCHAR(10) NOT NULL,
    period_start      DATE NOT NULL,
    period_end        DATE NOT NULL,
    generated_at      TIMESTAMP NOT NULL,
    source            VARCHAR(10),
    brew_count        INTEGER NOT NULL,
    average_rating    DOUBLE,
    top_bean_name     VARCHAR(50),
    most_used_method  VARCHAR(50),
    total_dose_grams  DOUBLE,
    brews_per_day     CLOB,
    method_breakdown  CLOB,
    rating_trend      CLOB,
    CONSTRAINT uq_report_user_period UNIQUE (user_id, period_type, period_start),
    FOREIGN KEY (user_id) REFERENCES "user"(id)
    );

-- Add origin discriminator to report tables that predate the `source` column (CREATE TABLE IF NOT
