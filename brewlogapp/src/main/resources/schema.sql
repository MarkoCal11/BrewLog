CREATE TABLE IF NOT EXISTS "user"(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username         VARCHAR(100) NOT NULL,
    password         VARCHAR(100) NOT NULL,
    email            VARCHAR(100) NOT NULL,
    role             VARCHAR(20),
    active           BOOLEAN NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMP,
    CONSTRAINT uq_user_username UNIQUE (username)
);

CREATE TABLE IF NOT EXISTS coffee_bean(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(50) NOT NULL,
    origin           VARCHAR(50) NOT NULL,
    roast_level       VARCHAR(15) NOT NULL,
    processing_method VARCHAR(50),
    roaster_name      VARCHAR(50) NOT NULL,
    roast_date        DATE,
    price             DOUBLE,
    altitude          INTEGER,
    tasting_notes     VARCHAR(255),
    favorite          BOOLEAN NOT NULL DEFAULT FALSE,
    weight_grams      INTEGER,
    user_id           BIGINT,
    photo_url         VARCHAR(255),
    finished          BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS brew_entry(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bean_id           BIGINT NOT NULL,
    user_id           BIGINT,
    "method"          VARCHAR(50) NOT NULL,
    grind_size        DOUBLE,
    water_temp_c      DOUBLE,
    rating            DOUBLE,
    brewed_at         TIMESTAMP NOT NULL,
    brew_time_seconds DOUBLE,
    dose_grams        DOUBLE NOT NULL,
    water_grams       DOUBLE,
    yield_grams       DOUBLE,
    notes            VARCHAR(100),
    FOREIGN KEY (bean_id) REFERENCES coffee_Bean(id)
);

CREATE TABLE IF NOT EXISTS flavor_note(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(50) NOT NULL,
    category         VARCHAR(50) NOT NULL,
    user_id          BIGINT,
    FOREIGN KEY (user_id) REFERENCES "user"(id)
);

CREATE TABLE IF NOT EXISTS coffee_bean_flavor_note(
    coffee_bean_id  BIGINT NOT NULL,
    flavor_note_id  BIGINT NOT NULL,
    PRIMARY KEY (coffee_bean_id, flavor_note_id),
    FOREIGN KEY (coffee_bean_id) REFERENCES coffee_bean(id),
    FOREIGN KEY (flavor_note_id) REFERENCES flavor_note(id)
    );

CREATE TABLE IF NOT EXISTS refresh_token(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash  VARCHAR(64) NOT NULL,
    user_id     BIGINT NOT NULL,
    expires_at  TIMESTAMP NOT NULL,
    used        BOOLEAN NOT NULL DEFAULT FALSE,
    remember_me BOOLEAN NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP NOT NULL,
    CONSTRAINT uq_refresh_token_token_hash UNIQUE (token_hash),
    FOREIGN KEY (user_id) REFERENCES "user"(id)
);
