CREATE TABLE IF NOT EXISTS cafe_location(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50) NOT NULL,
    city        VARCHAR(50),
    address     VARCHAR(100),
    rating      DOUBLE,
    instagram   VARCHAR(100),
    latitude    DOUBLE,
    longitude   DOUBLE,
    user_id     BIGINT
);
